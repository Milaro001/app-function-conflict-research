#!/usr/bin/env python3
"""Copy a generated report for offline readers, without the author's chat receiver."""
import argparse
import json
from pathlib import Path
import re
import shutil

SKILL = Path(__file__).resolve().parents[1]

def make_offline(source, output, home_url=None):
    source, output = Path(source).resolve(), Path(output).resolve()
    if source == output:
        raise ValueError('Use a separate output directory; the original report is preserved.')
    html = (source / 'report.html').read_text(encoding='utf-8')
    pattern = r'(<script\b[^>]*\bid=[\x27"]report-data[\x27"][^>]*>)(.*?)(</script>)'
    match = re.search(pattern, html, re.S)
    if not match:
        raise ValueError('Expected embedded report-data; rebuild with this Skill first.')
    data = json.loads(match.group(2))
    data['handoff'] = {'local_bridge': False}
    payload = json.dumps(data, ensure_ascii=False).replace('</', '<\\/')
    html = html[:match.start(2)] + payload + html[match.end(2):]
    start = html.index('const returnUrl=')
    end = html.index('function effectiveAction(', start)
    html = html[:start] + '''let refreshHandoff=null;
function resetReviewDock(){refreshHandoff=null;const dock=document.getElementById('review-dock');dock.replaceChildren();dock.hidden=true}
async function copyFeedback(text){try{await navigator.clipboard.writeText(text);return 'browser_clipboard'}catch(_){return null}}
''' + html[end:]
    start = html.index('function drawReview(root,i){')
    end = html.index('\nlet issueEntranceTimer=', start)
    review = (SKILL / 'assets/offline-review.js').read_text(encoding='utf-8')
    if home_url:
        if re.match(r'^(?:[a-z][a-z0-9+.-]*:|//|/)', home_url, re.I):
            raise ValueError('home_url must be a relative package path.')
        review = review.replace("home.href='../打开这里.html';", 'home.href='+json.dumps(home_url, ensure_ascii=False)+';')
    else:
        review = review.replace("const home=add(actions,'a','离线交付首页');home.href='../打开这里.html';", '')
    html = html[:start] + review + html[end:]
    html = html.replace("const storageKey='app-conflict-review:'+report.bundle_id;", "const storageKey='app-conflict-review:offline:'+report.bundle_id;")
    html = html.replace("const lines=['请继续处理这份'+report.app+'功能调研反馈。'", "const lines=[report.app+'离线阅读反馈（未自动提交）'")
    html = html.replace('aria-label="提交所选任务"', 'aria-label="导出离线反馈"')
    if any(x in html for x in ['codex://', '/api/session', '/api/submit', 'fetch(']):
        raise ValueError('Unexpected receiver code remains; no offline output was written.')
    # Product imagery generated by this Skill is embedded. Do not silently call a remote image offline.
    hero = data.get('analytics', {}).get('presentation', {}).get('hero', {})
    for image in hero.get('images', []) or ([hero['image']] if hero.get('image') else []):
        if not image.get('data', '').startswith('data:image/'):
            raise ValueError('Embed product images before making the offline report.')
    output.mkdir(parents=True, exist_ok=True)
    (output / 'report.html').write_text(html, encoding='utf-8')
    (output / 'report-data.json').write_text(json.dumps(data, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    if (source / 'evidence.csv').is_file():
        shutil.copy2(source / 'evidence.csv', output / 'evidence.csv')
    result = {'offline_copy': True, 'entry': 'report.html', 'receiver_included': False,
              'reader_feedback': 'local JSON export only', 'research_content_changed': False,
              'browser_check': 'not run by this command; test file:// with network disabled'}
    (output / 'offline-export.json').write_text(json.dumps(result, ensure_ascii=False, indent=2)+'\n', encoding='utf-8')
    return result

def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('report_directory', type=Path)
    parser.add_argument('--output', type=Path, required=True)
    parser.add_argument('--home', help='Relative path to an optional package homepage')
    args = parser.parse_args()
    try:
        print(json.dumps(make_offline(args.report_directory, args.output, args.home), ensure_ascii=False))
    except (ValueError, OSError, KeyError) as error:
        parser.exit(1, str(error)+'\n')

if __name__ == '__main__':
    main()
